// Synthetic data rooms for the itc-transfer playbook. All parties, documents and numbers are fictional.
// One term sheet, several data rooms: the rooms differ only in the facts listed in `RoomFacts`, so the same
// engine, prompts and playbook can be scored on a deal with planted issues (Cottonwood), a clean deal, and a
// deal with three of the issues resolved (perturbed). Expected answers live in evals/<room>/gold.json.

export type Block =
  | string
  | { h: string }
  | { table: string[][] }
  | { sig: string[] }
  | { pageBreak: true };

export interface SynthDoc {
  id: string;
  filename: string;
  letterhead: string;
  title: string;
  meta: string[];
  blocks: Block[];
}

/** The facts that vary between rooms. Everything else in the documents is identical. */
export interface RoomFacts {
  /** Folder under public/demo-data and evals. */
  room: string;
  /** Cost segregation report: network upgrades excluded from basis ($136.4M) or basis as estimated ($142.0M). */
  basisCut: boolean;
  /** Apprentice labor hours short of the 15% requirement (13.2%, cure unpaid) or met (16.0%). */
  apprenticeShort: boolean;
  /** Beginning of construction disputed between documents, or one documented 2025-12-22 start the IE confirms. */
  bocDisputed: boolean;
  /** Placed in service slips to February 2027, or stays November 30, 2026. */
  pisSlip: boolean;
  /** The PV module supplier's FEOC certification is missing, or received. */
  moduleCertMissing: boolean;
  /** Insurance binder: $55.0M limit with a PWA exclusion, or $66.385M with none. */
  insuranceShort: boolean;
  /** Insurance binder states 132 MWdc (a clerical mismatch) or 135 MWdc. */
  binderTypo: boolean;
  /** Seller counsel's email carries a line addressed to automated review tools. */
  injectedInstruction: boolean;
}

